// Package ast re-exports AST types and constants from internal/ast.
// This package is part of the public API surface for the ServalHQ fork of typescript-go.
package ast

import internal "github.com/microsoft/typescript-go/internal/ast"

// Core AST types

// Node is the fundamental AST node type.
type Node = internal.Node

// SourceFile represents a parsed TypeScript/JavaScript source file.
type SourceFile = internal.SourceFile

// Symbol represents a named entity in the TypeScript type system.
type Symbol = internal.Symbol

// SymbolTable maps symbol names to their Symbol instances.
type SymbolTable = internal.SymbolTable

// Diagnostic represents a compiler diagnostic (error, warning, etc.).
type Diagnostic = internal.Diagnostic

// Kind identifies the type of an AST node.
type Kind = internal.Kind

// NodeFlags represent additional information about a node.
type NodeFlags = internal.NodeFlags

// NodeList is a list of AST nodes.
type NodeList = internal.NodeList

// ModifierList is a list of modifier nodes.
type ModifierList = internal.ModifierList

// FileReference represents a reference to another file.
type FileReference = internal.FileReference

// HasFileName is an interface for entities that have a file name.
type HasFileName = internal.HasFileName

// SourceFileParseOptions configures how a source file is parsed.
type SourceFileParseOptions = internal.SourceFileParseOptions

// ExternalModuleIndicatorOptions controls external module detection.
type ExternalModuleIndicatorOptions = internal.ExternalModuleIndicatorOptions

// ImportAttributes represents import assertion/attribute nodes.
type ImportAttributes = internal.ImportAttributes

// NodeId is the unique identifier for an AST node.
type NodeId = internal.NodeId

